import { prisma } from "../../config/prisma";
import { getBillerDetailsService } from "./setuBiller.service";
import { getBillDetailsService } from "./setuBill.service";

export interface BbpsReceiptData {
  receiptNumber: string;
  receiptDate: string;
  internalTxnId: string;
  refID: string;
  bbpsRefNo: string;
  billerId: string;
  billerName: string;
  category: string;
  logoUrl?: string | null;
  amount: number;
  paymentMode: string;
  status: string;
  customerParams: Record<string, any>;
  customerName?: string;
  taxes?: number;
  fees?: number;
  notes?: string;
}

import { inMemoryTransactions } from "./setuPayment.service";

/**
 * Retrieves official BBPS receipt details for a transaction.
 */
export async function getTransactionReceiptService(
  txnIdentifier: string,
  ownerUserId?: string
): Promise<BbpsReceiptData | null> {
  let tx: any = null;

  try {
    tx = await prisma.bbpsTransaction.findFirst({
      where: {
        ...(ownerUserId ? { userId: ownerUserId } : {}),
        OR: [
          { id: txnIdentifier },
          { internalTxnId: txnIdentifier },
          { refID: txnIdentifier },
          { platformBillId: txnIdentifier },
        ],
      },
    });
  } catch (_e) {}

  const memCandidate = inMemoryTransactions.get(txnIdentifier);
  if (!tx && memCandidate && (!ownerUserId || memCandidate.userId === ownerUserId)) {
    const memTx = memCandidate;
    tx = {
      internalTxnId: memTx.internalTxnId,
      refID: memTx.refID,
      platformBillId: memTx.platformBillId,
      billerId: memTx.billerId,
      billerName: memTx.billerName,
      category: "Utilities",
      amount: memTx.amount,
      paymentInstrument: memTx.paymentMode || "UPI",
      status: memTx.status,
      bbpsRefNo: memTx.bbpsRefNo,
      receiptNumber: memTx.receiptNumber,
      receiptDate: memTx.receiptDate ? new Date(memTx.receiptDate) : new Date(),
      createdAt: new Date(),
    };
  }

  if (!tx) {
    return null;
  }

  const biller = await getBillerDetailsService(tx.billerId);
  let bill: any = null;
  try {
    bill = tx.platformBillId ? await getBillDetailsService(tx.platformBillId) : null;
  } catch (_e) {}

  const dateObj = tx.receiptDate || tx.createdAt;
  const dateStr = dateObj.toLocaleDateString("en-GB", {
    day: "2-digit",
    month: "short",
    year: "numeric",
  });
  const timeStr = dateObj.toLocaleTimeString("en-US", {
    hour: "2-digit",
    minute: "2-digit",
    hour12: true,
  });

  return {
    receiptNumber: tx.receiptNumber || `RCT-${tx.internalTxnId.slice(-8)}`,
    receiptDate: `${dateStr} · ${timeStr}`,
    internalTxnId: tx.internalTxnId,
    refID: tx.refID,
    bbpsRefNo: tx.bbpsRefNo || `BBPS${tx.refID.replace(/[^0-9]/g, "").slice(0, 10)}`,
    billerId: tx.billerId,
    billerName: tx.billerName,
    category: tx.category,
    logoUrl: biller?.logoUrl || null,
    amount: parseFloat(tx.amount.toString()),
    paymentMode: tx.paymentInstrument || "UPI",
    status: tx.status,
    customerParams: (tx.customerParams as any) || {},
    customerName: "Verified Consumer",
    taxes: bill?.taxes ? parseFloat(bill.taxes.toString()) : 0,
    fees: bill?.fees ? parseFloat(bill.fees.toString()) : 0,
    notes: "Official Bharat BillPay System (BBPS) electronic receipt generated by Setu COU.",
  };
}
